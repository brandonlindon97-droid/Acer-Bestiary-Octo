-- ClassicBestiary 2.5.3
-- Vanilla 1.12.1 / Turtle WoW / OctoWoW
--
-- Adds creature abilities directly to Blizzard's DEFAULT GameTooltip.
-- Normal hover: ability names + "(Ctrl for details)".
-- Hold Ctrl: ability names + descriptions.
--
-- Resolution strategy:
--   1) Native tooltip GUID APIs when available.
--   2) UnitCreatureID / UnitGUID on mouseover/npc.
--   3) C_CreatureInfo cache: match the visible tooltip name against the
--      database NPC IDs. This is the important fallback for clients where
--      UnitName("mouseover") works but UnitGUID/UnitCreatureID do not.
--   4) QuestieDB NPC name lookup, when Questie is installed.
--
-- The database is generated from the Turtle WoW/Tortoise creature_ability dataset.
-- It includes Turtle custom NPCs and the Vanilla 1.12-era creatures present in Turtle.
-- Only server-assigned NPC abilities are stored; pet-training-only false positives are not copied from the old database.

