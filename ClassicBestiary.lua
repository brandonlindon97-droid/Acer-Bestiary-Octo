local function CB_CtrlDown()
    if IsControlKeyDown then
        local ok, down = pcall(IsControlKeyDown)
        if ok then return down and true or false end
    end
    return CB_ctrlState
end

local function CB_GetTooltipHeader()
    if not GameTooltip or not GameTooltip:IsShown() then return nil end
    local fs = getglobal("GameTooltipTextLeft1")
    if fs and fs.GetText then
        local ok, text = pcall(fs.GetText, fs)
        if ok and text and text ~= "" then return text end
    end
    return nil
end

local function CB_GetTooltipUnit()
    local name, guid, token
    local tipName = CB_GetTooltipHeader()

    if GameTooltip then
        if GameTooltip.HasUnit and GameTooltip.GetUnitGUID then
            local ok, has = pcall(GameTooltip.HasUnit, GameTooltip)
            if ok and has then
                local ok2, n, g = pcall(GameTooltip.GetUnitGUID, GameTooltip)
                if ok2 and g then return n, g, nil, "tooltip-guid" end
            end
        end
        if GameTooltip.GetUnitGUID then
            local ok, n, g = pcall(GameTooltip.GetUnitGUID, GameTooltip)
            if ok and g then return n, g, nil, "tooltip-guid" end
        end
        if GameTooltip.GetUnit then
            local ok, n, t = pcall(GameTooltip.GetUnit, GameTooltip)
            if ok and t then
                if UnitGUID then
                    local ok2, g = pcall(UnitGUID, t)
                    if ok2 and g then return n, g, t, "tooltip-unit" end
                end
                if UnitCreatureID then
                    local ok2, id = pcall(UnitCreatureID, t)
                    if ok2 and id and id > 0 then return n, nil, t, "tooltip-creatureid" end
                end
            end
        end
    end

    local tokens = {"mouseover", "npc", "target", "focus"}
    local i = 1
    while tokens[i] do
        local t = tokens[i]
        local n, g, id
        if UnitName then
            local ok, nn = pcall(UnitName, t)
            if ok then n = nn end
        end
        if UnitGUID then
            local ok, gg = pcall(UnitGUID, t)
            if ok then g = gg end
        end
        if UnitCreatureID then
            local ok, ii = pcall(UnitCreatureID, t)
            if ok and ii and ii > 0 then id = ii end
        end

        if tipName and n and n == tipName and (g or id) then
            return n, g, t, id and "unit-creatureid" or "unit-guid"
        end
        if (t == "mouseover" or t == "npc") and (g or id) then
            return n, g, t, id and "unit-creatureid" or "unit-guid"
        end
        i = i + 1
    end

    if GetMouseFocus then
        local ok, focus = pcall(GetMouseFocus)
        if ok and focus and focus.unit then
            local t = focus.unit
            local n, g, id
            if UnitName then local ok2, nn = pcall(UnitName, t); if ok2 then n = nn end end
            if UnitGUID then local ok2, gg = pcall(UnitGUID, t); if ok2 then g = gg end end
            if UnitCreatureID then local ok2, ii = pcall(UnitCreatureID, t); if ok2 and ii and ii > 0 then id = ii end end
            if g or id then return n, g, t, id and "focus-creatureid" or "focus-guid" end
        end
    end

    return nil, nil, nil, nil
end

local function CB_GetNPCIDFromGUID(guid, token)
    if token and UnitCreatureID then
        local ok, id = pcall(UnitCreatureID, token)
        if ok and id and id > 0 then return id, "UnitCreatureID" end
    end

    if C_CreatureInfo and C_CreatureInfo.GetCreatureID and guid then
        local ok, id = pcall(C_CreatureInfo.GetCreatureID, guid)
        if ok and id and id > 0 then return id, "C_CreatureInfo.GetCreatureID" end
    end

    if guid and strsplit then
        local a, b, c, d, e, id = strsplit("-", guid)
        if a == "Creature" or a == "Pet" then
            id = tonumber(id)
            if id then return id, "hyphen-guid" end
        end
    end

    if guid and type(guid) == "string" then
        local hex = string.gsub(guid, "^0x", "")
        if string.len(hex) == 16 then
            local hi = tonumber(string.sub(hex, 1, 8), 16)
            local lo = tonumber(string.sub(hex, 9, 16), 16)
            if hi and lo then
                local upper = math.mod(hi, 256)
                local lower = math.floor(lo / 65536)
                local id = upper * 65536 + lower
                if id > 0 then return id, "raw-guid" end
            end
        elseif string.len(hex) == 8 then
            local lo = tonumber(hex, 16)
            if lo then
                local id = math.mod(math.floor(lo / 65536), 65536)
                if id > 0 then return id, "raw-8-guid" end
            end
        end
    end

    return nil, nil
end

local function CB_HasData(npcID)
    return npcID and DB and DB.map and DB.map[npcID] ~= nil
end

-- Build a stable list of only the NPC IDs that actually occur in this addon.
-- We resolve names lazily so login remains cheap.
local function CB_BuildResolveList()
    if CB_resolveList then return end
    CB_resolveList = {}
    CB_resolveCount = 0
    if DB and DB.map then
        for id, _ in pairs(DB.map) do
            CB_resolveCount = CB_resolveCount + 1
            CB_resolveList[CB_resolveCount] = id
        end
    end
end

local function CB_QuestieNPCName(id)
    -- Support both the old QuestieDB API and the newer LibQuestieDB API.
    local qdb = nil
    if QuestieDB then qdb = QuestieDB end

    if qdb then
        if qdb.QueryNPCSingle then
            local ok, name = pcall(qdb.QueryNPCSingle, qdb, id, "name")
            if ok and name and name ~= "" then return name end
        end
        if qdb.GetNPC then
            local ok, npc = pcall(qdb.GetNPC, qdb, id)
            if ok and npc then
                if npc.name then return npc.name end
                if npc.Name then return npc.Name end
                if type(npc) == "table" and npc[1] and type(npc[1]) == "string" then return npc[1] end
            end
        end
    end

    -- Current Questie/QuestieTDB exposes LibQuestieDB.Npc.Get(id, field).
    -- The public name field is field 1 in the generated NPC table.
    if LibQuestieDB and LibQuestieDB.Npc and LibQuestieDB.Npc.Get then
        local ok, name = pcall(LibQuestieDB.Npc.Get, id, 1)
        if ok and name and name ~= "" then return name end
        -- Some builds accept the string field name as well.
        local ok2, name2 = pcall(LibQuestieDB.Npc.Get, id, "name")
        if ok2 and name2 and name2 ~= "" then return name2 end
    end

    -- QuestieDB may be exposed through the standalone LibQuestieDB global.
    if _GLibQuestieDB and _GLibQuestieDB.Npc and _GLibQuestieDB.Npc.Get then
        local ok, name = pcall(_GLibQuestieDB.Npc.Get, id, 1)
        if ok and name and name ~= "" then return name end
        local ok2, name2 = pcall(_GLibQuestieDB.Npc.Get, id, "name")
        if ok2 and name2 and name2 ~= "" then return name2 end
    end

    return nil
end

local function CB_CreatureCacheName(id)
    if not C_CreatureInfo or not C_CreatureInfo.GetCreatureInfoByID then return nil end
    local ok, info = pcall(C_CreatureInfo.GetCreatureInfoByID, id)
    if ok and info and info.name and info.name ~= "" then return info.name end
    return nil
end

local function CB_NormalizeName(s)
    if not s then return nil end
    -- Tooltip names can carry color escapes. The world name normally does not,
    -- but stripping them makes the fallback tolerant of other UI addons.
    s = string.gsub(s, "|c%x%x%x%x%x%x%x%x", "")
    s = string.gsub(s, "|r", "")
    return s
end

