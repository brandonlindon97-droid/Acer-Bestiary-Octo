-- Resolve classic Spell.dbc tooltip value tokens such as $s1, $s2 and $s3.
-- The raw SpellRec description contains these tokens, but the old 1.12 tooltip
-- engine normally expands them before displaying the player-facing tooltip.
-- When we add the description ourselves with GameTooltip:AddLine(), we must
-- perform that expansion ourselves.
local function CB_GetSpellEffectValue(spellID, effectIndex)
    if not spellID or not effectIndex or effectIndex < 1 or effectIndex > 3 then return nil end

    local basePoints, baseDice, dieSides

    if GetSpellRecField then
        local okBP, bp = pcall(GetSpellRecField, spellID, "effectBasePoints")
        local okBD, bd = pcall(GetSpellRecField, spellID, "effectBaseDice")
        local okDS, ds = pcall(GetSpellRecField, spellID, "effectDieSides")

        if okBP and type(bp) == "table" then
            basePoints = bp[effectIndex] or bp[effectIndex - 1]
        end
        if okBD and type(bd) == "table" then
            baseDice = bd[effectIndex] or bd[effectIndex - 1]
        end
        if okDS and type(ds) == "table" then
            dieSides = ds[effectIndex] or ds[effectIndex - 1]
        end
    end

    -- GetSpellRec() is a useful fallback on Nampower builds where array
    -- fields are easier to access through the complete record.
    if (basePoints == nil or baseDice == nil or dieSides == nil) and GetSpellRec then
        local ok, rec = pcall(GetSpellRec, spellID)
        if ok and rec then
            local function arrValue(t, i)
                if type(t) ~= "table" then return nil end
                return t[i] or t[i - 1]
            end
            if basePoints == nil then basePoints = arrValue(rec.effectBasePoints, effectIndex) end
            if baseDice == nil then baseDice = arrValue(rec.effectBaseDice, effectIndex) end
            if dieSides == nil then dieSides = arrValue(rec.effectDieSides, effectIndex) end
        end
    end

    if type(basePoints) ~= "number" then return nil end
    if type(baseDice) ~= "number" then baseDice = 1 end
    if type(dieSides) ~= "number" or dieSides < 1 then dieSides = 1 end

    -- Vanilla stores fixed effect magnitudes in the DBC as value - 1;
    -- EffectBaseDice is the engine's additional base component. For normal
    -- fixed effects this produces the familiar BasePoints + 1 value.
    local minimum = basePoints + baseDice
    local maximum = minimum + dieSides - 1

    if maximum ~= minimum then
        return tostring(minimum) .. "-" .. tostring(maximum)
    end
    return tostring(minimum)
end

local function CB_GetSpellEffectAmplitude(spellID, effectIndex)
    if not spellID or not effectIndex or effectIndex < 1 or effectIndex > 3 then return nil end

    local amp
    if GetSpellRecField then
        local ok, value = pcall(GetSpellRecField, spellID, "effectAmplitude")
        if ok and type(value) == "table" then
            amp = value[effectIndex] or value[effectIndex - 1]
        end
    end

    if amp == nil and GetSpellRec then
        local ok, rec = pcall(GetSpellRec, spellID)
        if ok and rec and type(rec.effectAmplitude) == "table" then
            amp = rec.effectAmplitude[effectIndex] or rec.effectAmplitude[effectIndex - 1]
        end
    end

    if type(amp) ~= "number" then return nil end
    return amp / 1000
end

local function CB_FormatSeconds(value)
    if type(value) ~= "number" then return nil end
    if value == math.floor(value) then return tostring(value) end
    local rounded = math.floor(value * 10 + 0.5) / 10
    if rounded == math.floor(rounded) then return tostring(math.floor(rounded)) end
    return string.format("%.1f", rounded)
end

local function CB_GetSpellDurationSeconds(spellID)
    -- Nampower exposes the resolved SpellDuration value directly. It is in
    -- milliseconds, so convert to the seconds used by the classic $d token.
    if GetSpellDuration then
        local ok, duration = pcall(GetSpellDuration, spellID, 1)
        if ok and type(duration) == "number" and duration > 0 then
            return duration / 1000
        end
    end
    return nil
end

local function CB_FormatSpellDescription(text, spellID)
    if not text or text == "" then return text end

    -- Supports both local references ($s1) and classic cross-spell references
    -- such as $12345s1, where the number before 's' is another spell ID.
    text = string.gsub(text, "$(%d*)s([1-3])", function(refID, effectIndex)
        local id = spellID
        if refID and refID ~= "" then id = tonumber(refID) end
        local value = CB_GetSpellEffectValue(id, tonumber(effectIndex))
        if value ~= nil then return value end
        return "$" .. (refID or "") .. "s" .. effectIndex
    end)

    -- $t1/$t2/$t3 are effect tick intervals in classic spell descriptions.
    -- SpellRec stores EffectAmplitude in milliseconds.
    text = string.gsub(text, "$(%d*)t([1-3])", function(refID, effectIndex)
        local id = spellID
        if refID and refID ~= "" then id = tonumber(refID) end
        local value = CB_GetSpellEffectAmplitude(id, tonumber(effectIndex))
        local formatted = CB_FormatSeconds(value)
        if formatted then return formatted end
        return "$" .. (refID or "") .. "t" .. effectIndex
    end)

    -- $d is the spell's base duration, in seconds.  The raw token does not
    -- contain its unit, so add the unit explicitly.  Use minutes when the
    -- duration is a whole number of minutes (or otherwise cleanly expressed
    -- in minutes), and seconds for shorter durations.
    local function CB_FormatDuration(value)
        if type(value) ~= "number" or value <= 0 then return nil end
        if value >= 60 then
            local minutes = value / 60
            local rounded = math.floor(minutes * 10 + 0.5) / 10
            if rounded == math.floor(rounded) then
                rounded = math.floor(rounded)
            end
            return tostring(rounded) .. (rounded == 1 and " minute" or " minutes")
        end
        local seconds = CB_FormatSeconds(value)
        if not seconds then return nil end
        return seconds .. (value == 1 and " second" or " seconds")
    end

    text = string.gsub(text, "$(%d*)d", function(refID)
        local id = spellID
        if refID and refID ~= "" then id = tonumber(refID) end
        local value = CB_GetSpellDurationSeconds(id)
        local formatted = CB_FormatDuration(value)
        if formatted then return formatted end
        return "$" .. (refID or "") .. "d"
    end)

    return text
end

local function CB_GetSpellDescription(spellID)
    if not spellID then return nil end

    -- Nampower exposes the localized spell description directly on SpellRec.
    -- This is the important path for NPC spells: unlike the player spellbook
    -- APIs, it does not require the player to know/learn the spell.
    if GetSpellRecField then
        local fields = {"description", "description_lang", "Description"}
        local i = 1
        while fields[i] do
            local ok, text = pcall(GetSpellRecField, spellID, fields[i])
            if ok and text and text ~= "" then return text end
            i = i + 1
        end
    end

    if GetSpellRec then
        local ok, rec = pcall(GetSpellRec, spellID)
        if ok and rec then
            local text = rec.description or rec.description_lang or rec.Description
            if text and text ~= "" then return text end
        end
    end

    -- SuperWoW/older Turtle spell information path.
    if SpellInfo then
        local ok, name, rank, icon, minRange, maxRange, description = pcall(SpellInfo, spellID)
        if ok and description and description ~= "" then return description end
    end

    if GetSpellDescription then
        local ok, text = pcall(GetSpellDescription, spellID)
        if ok and text and text ~= "" then return text end
    end
    if C_Spell and C_Spell.GetSpellDescription then
        local ok, text = pcall(C_Spell.GetSpellDescription, spellID)
        if ok and text and text ~= "" then return text end
    end

    -- Last resort: ask a hidden Blizzard tooltip to build the spell tooltip.
    -- Try every spell-tooltip entry point and read both left and right columns.
    local scan = CB_GetScanner()
    if scan then
        local methods = {"SetSpellByID", "SetHyperlink", "SetSpell"}
        local i = 1
        while methods[i] do
            pcall(scan.ClearLines, scan)
            local loaded = false
            if methods[i] == "SetHyperlink" and scan.SetHyperlink then
                local ok = pcall(scan.SetHyperlink, scan, "spell:" .. tostring(spellID))
                loaded = ok
            elseif scan[methods[i]] then
                local ok = pcall(scan[methods[i]], scan, spellID)
                loaded = ok
            end

            if loaded then
                local parts = {}
                local n = 1
                while n <= 30 do
                    local left = getglobal("ClassicBestiaryScannerTextLeft" .. n)
                    local right = getglobal("ClassicBestiaryScannerTextRight" .. n)
                    if left and left.GetText then
                        local ok, text = pcall(left.GetText, left)
                        if ok and text and text ~= "" and n > 1 then table.insert(parts, text) end
                    end
                    if right and right.GetText then
                        local ok, text = pcall(right.GetText, right)
                        if ok and text and text ~= "" then table.insert(parts, text) end
                    end
                    n = n + 1
                end
                if table.getn(parts) > 0 then
                    pcall(scan.Hide, scan)
                    return table.concat(parts, "\n")
                end
            end
            i = i + 1
        end
        pcall(scan.Hide, scan)
    end

    return nil
end

local function CB_GetAbilityDescription(spellID)
    if DB.tip and DB.tip[spellID] then
        local tip = DB.tip[spellID]
        local textID = tip[1]
        if textID == 0 then return CB_FormatSpellDescription(CB_GetSpellDescription(spellID), spellID) end
        if DB.st and DB.st[textID] then return CB_FormatSpellDescription(DB.st[textID], spellID) end
    end
    return CB_FormatSpellDescription(CB_GetSpellDescription(spellID), spellID)
end

local function CB_HideTextureList(list)
    local i = 1
    while list[i] do
        local tex = list[i]
        if tex and tex.Hide then pcall(tex.Hide, tex) end
        if tex and tex.ClearAllPoints then pcall(tex.ClearAllPoints, tex) end
        i = i + 1
    end
end

local function CB_ClearFadingTextures()
    if CB_fadingTextures and table.getn and table.getn(CB_fadingTextures) > 0 then
        CB_HideTextureList(CB_fadingTextures)
    end
    CB_fadingTextures = {}
end

-- Keep ClassicBestiary icon frames as children of GameTooltip.  Creature
-- tooltips are explicitly hidden on mouse-leave by the guarded OnUpdate path,
-- while non-creature tooltips are left entirely to Blizzard.
local function CB_ClearState(fadeWithTooltip)
    -- fadeWithTooltip is retained for compatibility with older call sites.
    -- In 2.4.29 the synchronized fade is handled separately; normal state
    -- cleanup always hides the current icon frames immediately.
    CB_HideTextureList(CB_addedTextures)
    CB_addedTextures = {}
    CB_lastKey = nil
    CB_lastTipName = nil
    CB_lastMode = nil
    CB_baseLines = 0
    CB_addedLines = 0
end

local function CB_StartSynchronizedFade()
    if CB_syncFadeActive then return end
    if not GameTooltip or not GameTooltip:IsShown() then
        CB_ClearState()
        return
    end
    CB_syncFadeActive = true
    CB_syncFadeElapsed = 0

    -- Start both at the same opacity.  The icon frames are children of the
    -- tooltip, so their visual opacity follows the same parent alpha.
    pcall(GameTooltip.SetAlpha, GameTooltip, 1)
    local i = 1
    while CB_addedTextures[i] do
        local frame = CB_addedTextures[i]
        if frame then
            pcall(frame.SetAlpha, frame, 1)
            pcall(frame.Show, frame)
        end
        i = i + 1
    end
end

local function CB_StopSynchronizedFade(hideTooltip)
    CB_syncFadeActive = false
    CB_syncFadeElapsed = 0
    if GameTooltip then
        pcall(GameTooltip.SetAlpha, GameTooltip, 1)
    end
    if hideTooltip and GameTooltip and GameTooltip:IsShown() then
        pcall(GameTooltip.Hide, GameTooltip)
    end
end

local function CB_UpdateSynchronizedFade(elapsed)
    if not CB_syncFadeActive then return end
    CB_syncFadeElapsed = CB_syncFadeElapsed + (elapsed or 0)
    local progress = CB_syncFadeElapsed / CB_SYNC_FADE_TIME
    if progress >= 1 then
        local i = 1
        while CB_addedTextures[i] do
            local frame = CB_addedTextures[i]
            if frame then pcall(frame.SetAlpha, frame, 0) end
            i = i + 1
        end
        CB_StopSynchronizedFade(true)
        CB_HideTextureList(CB_addedTextures)
        CB_addedTextures = {}
        CB_lastKey = nil
        CB_lastTipName = nil
        CB_lastMode = nil
        CB_baseLines = 0
        CB_addedLines = 0
        return
    end

    local alpha = 1 - progress
    pcall(GameTooltip.SetAlpha, GameTooltip, alpha)
    local i = 1
    while CB_addedTextures[i] do
        local frame = CB_addedTextures[i]
        if frame then pcall(frame.SetAlpha, frame, 1) end
        i = i + 1
    end
end

-- 2.5.0: The database now comes directly from Tortoise's derived creature_ability table.
-- Do not globally filter pet spells here: if a Turtle NPC is genuinely assigned
-- a spell that is also trainable by Hunter pets, it is still a real NPC ability.

local function CB_AddAbilityLines(npcID, withDescriptions)
    local abilities = DB.map[npcID]
    if not abilities then return 0 end
    local added = 0
    local i = 1

    while abilities[i] do
        local spellID = abilities[i]
        local name = CB_GetSpellName(spellID)
        if not name then
            name = "Spell " .. tostring(spellID)
        end

        -- IMPORTANT: never change the FontString's vertical anchor. The
        -- tooltip engine has already laid out this line correctly. Reserve
        -- horizontal room with leading spaces, while the icon itself is
        -- anchored to the tooltip's INSIDE left edge.
        GameTooltip:AddLine("      " .. name)
        added = added + 1

        local lineNo = GameTooltip:NumLines()
        local fs = getglobal("GameTooltipTextLeft" .. lineNo)
        local texture = CB_GetSpellTexture(spellID)

        if fs and texture and texture ~= "" and CreateFrame then
            local okFrame, iconFrame = pcall(CreateFrame, "Frame", nil, GameTooltip)
            if okFrame and iconFrame then
                local icon = iconFrame:CreateTexture(nil, "ARTWORK")
                if icon then
                    pcall(icon.SetTexture, icon, texture)
                    pcall(icon.SetWidth, icon, 14)
                    pcall(icon.SetHeight, icon, 14)
                    pcall(icon.ClearAllPoints, icon)
                    pcall(icon.SetPoint, icon, "LEFT", fs, "LEFT", -1, 1)
                    pcall(iconFrame.SetWidth, iconFrame, 14)
                    pcall(iconFrame.SetHeight, iconFrame, 14)
                    pcall(iconFrame.ClearAllPoints, iconFrame)
                    pcall(iconFrame.SetPoint, iconFrame, "LEFT", fs, "LEFT", -1, 1)
                    pcall(iconFrame.Show, iconFrame)
                    table.insert(CB_addedTextures, iconFrame)
                end
            end
        end

        if withDescriptions then
            local description = CB_GetAbilityDescription(spellID)
            if description and description ~= "" then
                GameTooltip:AddLine(description, 0.8, 0.8, 0.8, true)
                added = added + 1
            end
        end
        i = i + 1
    end
    return added
end

local function CB_RebuildUnderlyingTooltip(guid, oldToken, tipName)
    local token = oldToken

    -- On this Vanilla/Turtle client the engine-created world tooltip may not
    -- expose a GUID or tooltip unit token at all.  In that case the visible
    -- creature is still available as mouseover, so use that token to rebuild
    -- the original Blizzard tooltip before changing between NORMAL and CTRL.
    if not token and tipName and UnitName then
        local ok, mouseName = pcall(UnitName, "mouseover")
        if ok and mouseName and mouseName == tipName then
            token = "mouseover"
        end
    end

    if not token and guid and UnitTokenFromGUID then
        local ok, t = pcall(UnitTokenFromGUID, guid)
        if ok then token = t end
    end
    if not token or not GameTooltip.SetUnit then return false end

    if guid and UnitGUID then
        local ok, current = pcall(UnitGUID, token)
        if ok and current and current ~= guid then return false end
    end

    CB_busy = true
    -- Some Vanilla/Turtle tooltip paths can retain already-appended AddLine
    -- content when SetUnit() is called on the currently visible tooltip.
    -- Clear the frame first so every mode change starts from one clean native
    -- tooltip, then let SetUnit() repopulate Blizzard's unit lines.
    if GameTooltip.ClearLines then
        pcall(GameTooltip.ClearLines, GameTooltip)
    end
    local ok = pcall(GameTooltip.SetUnit, GameTooltip, token)
    CB_busy = false
    return ok
end

local function CB_ProcessTooltip(force)
    if CB_busy then return end
    if not GameTooltip or not GameTooltip:IsShown() then
        if CB_lastKey then CB_ClearState() end
        return
    end

    local tipName = CB_GetTooltipHeader()

    -- A world-unit tooltip can remain visible for a frame or more after
    -- UPDATE_MOUSEOVER_UNIT fires.  If the mouse is already off the creature,
    -- the header is stale.  Do NOT resolve that stale name and append our block
    -- again; doing so is what caused the repeated Bestiary blocks seen when
    -- Ctrl was spammed or the cursor left the unit.
    if UnitName and tipName then
        local okMouse, mouseName = pcall(UnitName, "mouseover")
        local normTipName = CB_NormalizeName(tipName)
        local normMouseName = CB_NormalizeName(mouseName)
        if okMouse and (not normMouseName or normMouseName ~= normTipName) then
            -- The tooltip may be an item, spell, quest, etc.  Never hide the
            -- shared GameTooltip merely because its header does not match the
            -- current mouseover unit.  Only clear ClassicBestiary's own state;
            -- Blizzard remains responsible for showing/hiding non-unit tips.
            -- This is especially important when moving directly from a creature
            -- to an item: the old fade code could call GameTooltip:Hide() and
            -- make every item tooltip disappear immediately.
            if CB_lastKey then
                CB_ClearState()
            end
            return
        end
    end

    local name, guid, token, source = CB_GetTooltipUnit()

    -- On some Vanilla/Turtle builds the world tooltip is engine-generated and
    -- the unit APIs expose only UnitName. If mouseover is valid, rebuilding
    -- the same default tooltip through Lua can populate the tooltip's unit
    -- state even though the original engine pass did not expose it.
    if tipName and UnitName and GameTooltip and GameTooltip.SetUnit and not guid then
        local okName, mouseName = pcall(UnitName, "mouseover")
        if okName and mouseName and CB_NormalizeName(mouseName) == CB_NormalizeName(tipName) then
            pcall(GameTooltip.SetUnit, GameTooltip, "mouseover")
            name, guid, token, source = CB_GetTooltipUnit()
            tipName = CB_GetTooltipHeader() or tipName
        end
    end
    local npcID, idSource = CB_GetNPCIDFromGUID(guid, token)

    -- Name resolution is deliberately after all native paths. This makes the
    -- addon work on the exact client state where only UnitName(mouseover) is
    -- available.
    if not npcID and tipName then
        npcID, idSource = CB_ResolveNPCByName(tipName)
        if npcID then source = idSource end
    end

    if not npcID or not CB_HasData(npcID) then
        return
    end

    local stateKey = (guid or "NAME:" .. tostring(tipName or name or "?") .. ":NPC:" .. tostring(npcID))
    -- Details are a HOLD action, not a toggle: while Ctrl is physically down
    -- show descriptions; as soon as Ctrl is released return to the compact
    -- tooltip.
    local mode = CB_ctrlState and "CTRL" or "NORMAL"
    local lines = GameTooltip:NumLines()
    local changed = force or stateKey ~= CB_lastKey or mode ~= CB_lastMode

    if not changed and CB_addedLines > 0 and lines < (CB_baseLines + CB_addedLines) then
        changed = true
    end
    if not changed then return end

    if stateKey ~= CB_lastKey or mode ~= CB_lastMode then
        -- The tooltip itself is rebuilt by SetUnit(), but child Texture frames
        -- that we created are NOT automatically hidden.  Clear them BEFORE
        -- rebuilding or they remain visible and produce duplicate icons.
        CB_ClearState()
        if CB_RebuildUnderlyingTooltip(guid, token, tipName) then
            -- SetUnit clears/rebuilds the Blizzard tooltip, so recalculate the
            -- number of native lines before appending Bestiary lines.
            lines = GameTooltip:NumLines()
        end
    end

    CB_lastKey = stateKey
    CB_lastTipName = tipName or name
    CB_lastMode = mode
    CB_baseLines = lines
    CB_addedLines = 0

    CB_addedLines = CB_AddAbilityLines(npcID, mode == "CTRL")
    if mode ~= "CTRL" then
        GameTooltip:AddLine("(Ctrl for details)", 0.8, 0.8, 0.8)
        CB_addedLines = CB_addedLines + 1
    end

    if CB_addedLines > 0 then
        if GameTooltip:GetWidth() > 700 then GameTooltip:SetWidth(700) end
        GameTooltip:Show()
    end
end

local function CB_OnUpdate(self, elapsed)
    CB_elapsed = CB_elapsed + (elapsed or arg1 or 0)
    -- 2.4.33: Creature tooltips should disappear immediately when the mouse
    -- leaves the creature.  Do this ONLY when ClassicBestiary currently owns
    -- the visible tooltip state and its header is still the creature we added
    -- to.  Item/spell/quest tooltips are not touched.
    if GameTooltip and GameTooltip:IsShown() and CB_lastKey and CB_lastTipName then
        local tipName = CB_GetTooltipHeader()
        local okMouse, mouseName = false, nil
        if UnitName then
            okMouse, mouseName = pcall(UnitName, "mouseover")
        end
        if okMouse and not mouseName and tipName == CB_lastTipName then
            pcall(GameTooltip.Hide, GameTooltip)
            return
        end
    end
    if CB_elapsed < 0.03 then return end
    CB_elapsed = 0

    local ctrlDown = false
    if IsControlKeyDown then
        local ok, down = pcall(IsControlKeyDown)
        if ok then ctrlDown = down and true or false end
    end

    -- Ctrl is a HOLD modifier: details exist only while the physical Ctrl
    -- key is down.  Rebuild only when the state actually changes so repeated
    -- OnUpdate ticks cannot stack lines or icons.
    if ctrlDown ~= CB_ctrlState then
        CB_ctrlState = ctrlDown
        CB_detailsToggle = ctrlDown
        CB_lastMode = nil
        CB_lastKey = nil
        if GameTooltip and GameTooltip:IsShown() then
            CB_ProcessTooltip(true)
        end
    end
    CB_prevCtrlDown = ctrlDown

    if not GameTooltip or not GameTooltip:IsShown() then
        CB_prevCtrlDown = false
        CB_ClearFadingTextures()
    end

    CB_ProcessTooltip(false)
end

-- Do not hook OnTooltipSetUnit here. On this client, calling SetUnit()
-- ourselves can fire the same hook while the tooltip is being rebuilt, which
-- can cause the Bestiary block to be appended repeatedly. The OnUpdate path
-- below is sufficient and is deliberately idempotent.

local function CB_OnEvent()
    if event == "PLAYER_ENTERING_WORLD" then
        CB_detailsToggle = false
        CB_ctrlState = false
        CB_prevCtrlDown = false
        CB_ClearState()
        return
    end
    if event == "UPDATE_MOUSEOVER_UNIT" then
        -- Do not hide GameTooltip here. UPDATE_MOUSEOVER_UNIT also participates
        -- in transitions between world-unit and non-unit tooltips, and on this
        -- client it does not reliably mean that the visible tooltip is a stale
        -- unit tooltip. Blizzard owns the tooltip lifecycle; ClassicBestiary only
        -- cleans up its own appended state in OnUpdate/OnHide.
        return
    end
    -- Ctrl is polled from OnUpdate below instead of relying on
    -- MODIFIER_STATE_CHANGED.  Some Vanilla/Turtle builds do not deliver that
    -- event consistently to addon frames, while IsControlKeyDown() is present.
end

local frame = CreateFrame("Frame", "ClassicBestiaryEvents")
frame:RegisterEvent("PLAYER_ENTERING_WORLD")
frame:RegisterEvent("UPDATE_MOUSEOVER_UNIT")
frame:SetScript("OnEvent", CB_OnEvent)

if GameTooltip and GameTooltip.HookScript then
    GameTooltip:HookScript("OnUpdate", CB_OnUpdate)
    GameTooltip:HookScript("OnHide", function()
        CB_syncFadeActive = false
        CB_syncFadeElapsed = 0
        pcall(GameTooltip.SetAlpha, GameTooltip, 1)
        CB_ClearFadingTextures()
        CB_HideTextureList(CB_addedTextures)
        CB_addedTextures = {}
        CB_lastKey = nil
        CB_lastTipName = nil
        CB_lastMode = nil
        CB_baseLines = 0
        CB_addedLines = 0
    end)
else
    frame:SetScript("OnUpdate", CB_OnUpdate)
end

