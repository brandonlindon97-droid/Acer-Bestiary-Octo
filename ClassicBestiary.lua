-- Resolve a tooltip name to one of the NPC IDs that has ability data.
-- This is the critical fallback for the exact state shown by the user's debug:
-- UnitName("mouseover") works, but UnitGUID/UnitCreatureID are nil.
local function CB_ResolveNPCByName(tipName)
    tipName = CB_NormalizeName(tipName)
    if not tipName or tipName == "" then return nil, nil end

    if CB_nameCache[tipName] then
        return CB_nameCache[tipName], "name-cache"
    end

    local known = CB_KnownNPCIDByName(tipName)
    if known and CB_HasData(known) then
        CB_nameCache[tipName] = known
        return known, "built-in-name"
    end

    -- 2.5.1: the Turtle DB itself contains the authoritative NPC names.
    -- Prefer this local map before optional ClassicAPI/Questie lookups so the
    -- addon works even when UnitGUID, UnitCreatureID, C_CreatureInfo and Questie
    -- are all unavailable on the Vanilla/Turtle client. Only unique names are
    -- included; ambiguous names are left for native GUID/ID paths.
    local dbKnown = CB_DBNameToNPC[tipName]
    if dbKnown and CB_HasData(dbKnown) then
        CB_nameCache[tipName] = dbKnown
        return dbKnown, "db-name"
    end

    CB_BuildResolveList()

    -- First pass: ClassicAPI creature cache, if present.
    if C_CreatureInfo and C_CreatureInfo.GetCreatureInfoByID then
        local i = 1
        while i <= CB_resolveCount do
            local id = CB_resolveList[i]
            local name = CB_CreatureCacheName(id)
            if name and name == tipName then
                CB_nameCache[tipName] = id
                return id, "C_CreatureInfo.GetCreatureInfoByID"
            end
            i = i + 1
        end
    end

    -- Second pass: Questie database, if installed.
    if QuestieDB or QuestieLoader or LibQuestieDB or _GLibQuestieDB then
        local i = 1
        while i <= CB_resolveCount do
            local id = CB_resolveList[i]
            local name = CB_QuestieNPCName(id)
            if name and name == tipName then
                CB_nameCache[tipName] = id
                return id, "QuestieDB"
            end
            i = i + 1
        end
    end

    return nil, nil
end

local CB_scanTooltip = nil
local function CB_GetScanner()
    if CB_scanTooltip then return CB_scanTooltip end
    if not CreateFrame then return nil end
    local ok, scan = pcall(CreateFrame, "GameTooltip", "ClassicBestiaryScanner", UIParent, "GameTooltipTemplate")
    if not ok or not scan then
        -- Some 1.12 clients reject a parent/template combination here.
        ok, scan = pcall(CreateFrame, "GameTooltip", "ClassicBestiaryScanner", nil, "GameTooltipTemplate")
    end
    if not ok or not scan then return nil end
    CB_scanTooltip = scan
    pcall(scan.SetOwner, scan, scan, "ANCHOR_NONE")
    return CB_scanTooltip
end

local function CB_ScanSpell(spellID)
    local scan = CB_GetScanner()
    if not scan then return nil, nil, nil end

    pcall(scan.ClearLines, scan)

    local loaded = false
    if scan.SetSpellByID then
        local ok = pcall(scan.SetSpellByID, scan, spellID)
        if ok then loaded = true end
    end
    if not loaded and scan.SetHyperlink then
        local ok = pcall(scan.SetHyperlink, scan, "spell:" .. tostring(spellID))
        if ok then loaded = true end
    end
    if not loaded and scan.SetSpell then
        -- A few 1.12 derivatives expose SetSpell rather than accepting a
        -- spell hyperlink on a hidden scanner tooltip.
        local ok = pcall(scan.SetSpell, scan, spellID)
        if ok then loaded = true end
    end
    if not loaded then return nil, nil, nil end

    local name = nil
    local lines = {}
    local i = 1
    while i <= 30 do
        local fs = getglobal("ClassicBestiaryScannerTextLeft" .. i)
        if fs and fs.GetText then
            local ok, text = pcall(fs.GetText, fs)
            if ok and text and text ~= "" then
                if i == 1 then name = text else table.insert(lines, text) end
            end
        end
        i = i + 1
    end

    local desc = nil
    if table.getn(lines) > 0 then desc = table.concat(lines, "\n") end
    pcall(scan.Hide, scan)
    return name, desc, true
end

local function CB_ParseSpellLinkName(link)
    if not link then return nil end
    -- Classic spell links are |cff71d5ff|Hspell:ID:0|h[Spell Name]|h|r.
    local _, _, name = string.find(link, "|h%[(.-)%]|h")
    if name and name ~= "" then return name end
    return nil
end

local function CB_GetSpellRecName(spellID)
    -- Nampower/SuperAPI exposes the client SpellRec database to Lua.
    -- This is the most reliable arbitrary-spell name lookup on Turtle/Vanilla
    -- when stock GetSpellInfo/GetSpellLink are unavailable.
    if GetSpellRecField then
        local ok, name = pcall(GetSpellRecField, spellID, "name")
        if ok and name and name ~= "" then return name end
    end
    if GetSpellRec then
        local ok, rec = pcall(GetSpellRec, spellID)
        if ok and rec then
            if rec.name and rec.name ~= "" then return rec.name end
            if rec.name_lang and rec.name_lang ~= "" then return rec.name_lang end
            if rec.Name and rec.Name ~= "" then return rec.Name end
        end
    end
    return nil
end

local function CB_CleanSpellDisplayName(name)
    if not name then return nil end
    -- Some Turtle/Vanilla spell APIs can return a display string containing
    -- inline texture markup or a full spell hyperlink. We create the icon as
    -- a real Texture object below, so remove any embedded icon markup here.
    name = string.gsub(name, "|T[^|]*|t", "")
    name = string.gsub(name, "|A[^|]*|a", "")
    local _, _, linked = string.find(name, "|h%[(.-)%]|h")
    if linked and linked ~= "" then name = linked end
    name = string.gsub(name, "|c%x%x%x%x%x%x%x%x", "")
    name = string.gsub(name, "|r", "")
    name = string.gsub(name, "^%s+", "")
    name = string.gsub(name, "%s+$", "")
    if name == "" then return nil end
    return name
end

local function CB_GetSpellName(spellID)
    local recName = CB_GetSpellRecName(spellID)
    if recName then return CB_CleanSpellDisplayName(recName) end

    -- ClassicAPI exposes GetSpellInfo(spellID), but stock 1.12 does not.
    if GetSpellInfo then
        local ok, name = pcall(GetSpellInfo, spellID)
        if ok and name and name ~= "" then return CB_CleanSpellDisplayName(name) end
    end
    if C_Spell and C_Spell.GetSpellName then
        local ok, name = pcall(C_Spell.GetSpellName, spellID)
        if ok and name and name ~= "" then return CB_CleanSpellDisplayName(name) end
    end

    -- ClassicAPI also exposes GetSpellLink(spellID) for arbitrary spell IDs.
    -- This gives us the real localized spell name even when GetSpellInfo is
    -- absent from the user's client.
    if GetSpellLink then
        local ok, link = pcall(GetSpellLink, spellID)
        if ok then
            local name = CB_ParseSpellLinkName(link)
            if name then return CB_CleanSpellDisplayName(name) end
        end
    end
    if C_Spell and C_Spell.GetSpellLink then
        local ok, link = pcall(C_Spell.GetSpellLink, spellID)
        if ok then
            local name = CB_ParseSpellLinkName(link)
            if name then return CB_CleanSpellDisplayName(name) end
        end
    end

    local name = CB_ScanSpell(spellID)
    if name and name ~= "" then return CB_CleanSpellDisplayName(name) end
    if GameTooltip and GameTooltip.SetSpellByID then
        local scan = CB_GetScanner()
        if scan then
            pcall(scan.ClearLines, scan)
            local ok = pcall(scan.SetSpellByID, scan, spellID)
            if ok then
                local fs = getglobal("ClassicBestiaryScannerTextLeft1")
                if fs and fs.GetText then
                    local ok2, text = pcall(fs.GetText, fs)
                    if ok2 and text and text ~= "" then
                        pcall(scan.Hide, scan)
                        return CB_CleanSpellDisplayName(text)
                    end
                end
            end
            pcall(scan.Hide, scan)
        end
    end
    return nil
end

local function CB_GetSpellTexture(spellID)
    if not spellID then return nil end

    -- Explicit compatibility fallback for the original test spell.
    if CB_KnownSpellTexture[spellID] then return CB_KnownSpellTexture[spellID] end

    -- Nampower's SpellRec database is the preferred arbitrary-spell lookup on
    -- Turtle/Vanilla. GetSpellRecField(spellID, "spellIconID") gives us the
    -- SpellIcon.dbc record, and GetSpellIconTexture converts that record into
    -- the actual Interface\Icons\... texture path. This works for NPC spells
    -- even when the player does not know the spell.
    if GetSpellRecField and GetSpellIconTexture then
        local okID, spellIconID = pcall(GetSpellRecField, spellID, "spellIconID")
        if okID and spellIconID then
            local okTexture, icon = pcall(GetSpellIconTexture, spellIconID)
            if okTexture and icon and icon ~= "" then
                return icon
            end
        end
    end

    -- Some Nampower builds expose the same fields through GetSpellRec().
    if GetSpellRec and GetSpellIconTexture then
        local okRec, rec = pcall(GetSpellRec, spellID)
        if okRec and rec and rec.spellIconID then
            local okTexture, icon = pcall(GetSpellIconTexture, rec.spellIconID)
            if okTexture and icon and icon ~= "" then
                return icon
            end
        end
    end

    -- ClassicAPI may expose the icon directly through GetSpellInfo.
    if GetSpellInfo then
        local ok, _, _, icon = pcall(GetSpellInfo, spellID)
        if ok and icon and icon ~= "" then return icon end
    end

    if C_Spell and C_Spell.GetSpellTexture then
        local ok, icon = pcall(C_Spell.GetSpellTexture, spellID)
        if ok and icon and icon ~= "" then return icon end
    end

    if GetSpellTexture then
        -- Some Turtle/ClassicAPI builds extend GetSpellTexture to accept an
        -- arbitrary spell ID. Stock 1.12 expects a spellbook slot, so protect
        -- this call and only accept a plausible texture path.
        local ok, icon = pcall(GetSpellTexture, spellID)
        if ok and icon and icon ~= "" then return icon end
    end

    -- Last-resort icon extraction: render the spell in the scanner tooltip and
    -- inspect the first line's text for the standard |Ttexture:...|t markup.
    local scan = CB_GetScanner()
    if scan then
        pcall(scan.ClearLines, scan)
        local loaded = false
        if scan.SetSpellByID then
            local ok = pcall(scan.SetSpellByID, scan, spellID)
            if ok then loaded = true end
        end
        if not loaded and scan.SetHyperlink then
            local ok = pcall(scan.SetHyperlink, scan, "spell:" .. tostring(spellID))
            if ok then loaded = true end
        end
        if not loaded and scan.SetSpell then
            local ok = pcall(scan.SetSpell, scan, spellID)
            if ok then loaded = true end
        end
        if loaded then
            local fs = getglobal("ClassicBestiaryScannerTextLeft1")
            if fs and fs.GetText then
                local ok, text = pcall(fs.GetText, fs)
                if ok and text then
                    local _, _, texture = string.find(text, "|T([^:|]+):")
                    if texture and texture ~= "" then return texture end
                end
            end
        end
        pcall(scan.Hide, scan)
    end
    return nil
end

